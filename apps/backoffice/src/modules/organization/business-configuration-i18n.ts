export function useBusinessConfigurationI18n() {
  const { locale, copy: globalCopy } = useBackofficeLocalization();
  const copy = useCallback(
    (value: string) => configurationCopy[value]?.[locale] ?? globalCopy(value),
    [globalCopy, locale],
  );
  return { locale, copy };
}
